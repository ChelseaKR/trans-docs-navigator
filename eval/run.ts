// Eval CLI. Runs the harness, writes the committed report artifacts
// (docs/audits/eval-report.{md,json}), and returns a CI exit code.

import { writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { REPO_ROOT } from "../api/corpus.ts";
import { runEval } from "./harness.ts";
import { pass, fail } from "../scripts/util.ts";

const report = runEval();

const pct = (n: number) => `${(n * 100).toFixed(1)}%`;
const mark = (b: boolean) => (b ? "✅" : "❌");

const md = `# Eval Report — Trans Docs Navigator

> Generated by \`make eval\` for evaluation date **${report.today}**.
> Deterministic: the same inputs always yield this verdict.
> **Overall: ${report.passed ? "PASS ✅" : "FAIL ❌"}**

## Metrics

| Metric | Value | Threshold | n | Gate |
|--------|------:|----------:|--:|:----:|
${report.metrics
  .map((m) => `| ${m.name} | ${pct(m.value)} | ${pct(m.threshold)} | ${m.n} | ${mark(m.pass)} |`)
  .join("\n")}

## Disaggregated accuracy (bias audit §B)

| Segment | Accuracy | n | Gate |
|---------|---------:|--:|:----:|
${report.segment_accuracy.map((s) => `| ${s.segment} | ${pct(s.value)} | ${s.n} | ${mark(s.pass)} |`).join("\n")}

## Jurisdiction readiness (M6 — add only as each passes review)

Mechanically-ready = has current corpus + gold coverage + meets the accuracy bar.
**Launch-cleared is review-gated (named-human verification + counsel) and is OPEN for all.**

| Jurisdiction | Records | Current | Gold items | Accuracy | Mechanically ready | Human-verified | Launch-cleared |
|--------------|--------:|--------:|-----------:|---------:|:------------------:|:--------------:|:--------------:|
${report.jurisdiction_readiness
  .map(
    (j) =>
      `| ${j.jurisdiction} | ${j.records} | ${j.current_records} | ${j.gold_items} | ${pct(j.accuracy)} | ${mark(j.mechanically_ready)} | ${mark(j.verification_complete)} | ${mark(j.launch_cleared)} |`,
  )
  .join("\n")}

## Metamorphic properties

Paired-query invariants run against BOTH retrievers (the seam FIX-11 gates for a swap):
paraphrase stability, jurisdiction sensitivity, filter monotonicity, and (weaker,
FIX-03-dependent) EN/ES citation-shape consistency.

| Property | Retriever | Gate |
|----------|-----------|:----:|
${report.metamorphic.map((m) => `| ${m.name} | ${m.retrieverName} | ${mark(m.passed)} |`).join("\n")}

## Items

| Item | Suite | Segment | Result | Notes |
|------|-------|---------|:------:|-------|
${report.items
  .map(
    (i) =>
      `| ${i.id} | ${i.suite} | ${i.segment.jurisdiction}/${i.segment.language} | ${mark(i.passed)} | ${i.notes.join("; ")} |`,
  )
  .join("\n")}

## Gold-set provenance (eval validity)

| Property | Value |
|----------|-------|
| Independently authored | ${mark(report.gold_provenance.independent_author)} |
| Gold author | ${report.gold_provenance.gold_author} |
| Corpus author | ${report.gold_provenance.corpus_author} |
| Reviewed by | ${report.gold_provenance.reviewed_by ?? "—"} |

${report.gold_provenance.independent_author
  ? "_Gold set is independently authored — accuracy is a real measurement._"
  : "_⚠️ Gold set is co-authored with the corpus, so accuracy is partly self-consistent rather than independently earned. No jurisdiction may be launch-cleared until this is replaced by an independently-authored expert gold set (OPEN review-gate #2)._"}

---
_Scope note: ${report.gold_provenance.note ?? "see docs/audits/data-card.md"}_
`;

// Test-only override (tests/gate-efficacy): a poisoned run must not overwrite the
// committed audit artifacts with a deliberately-failing report. Unset in production.
const REPORT_DIR = process.env.EVAL_REPORT_DIR ?? join(REPO_ROOT, "docs", "audits");

writeFileSync(join(REPORT_DIR, "eval-report.md"), md);
writeFileSync(join(REPORT_DIR, "eval-report.json"), JSON.stringify(report, null, 2) + "\n");

for (const m of report.metrics) {
  console.log(`     ${mark(m.pass)} ${m.name}: ${pct(m.value)} (≥ ${pct(m.threshold)}, n=${m.n})`);
}
for (const s of report.segment_accuracy) {
  if (!s.pass) console.log(`     ❌ segment ${s.segment}: ${pct(s.value)} (n=${s.n})`);
}
for (const m of report.metamorphic) {
  if (!m.passed) console.log(`     ❌ metamorphic ${m.name} [${m.retrieverName}]: ${m.detail}`);
}

const reportLabel = relative(REPO_ROOT, REPORT_DIR) || REPORT_DIR;

if (!report.passed) fail("eval", `one or more eval gates below threshold (see ${reportLabel}/eval-report.md)`);
pass("eval", `groundedness/accuracy/refusal/coverage gates met; report written to ${reportLabel}/`);
